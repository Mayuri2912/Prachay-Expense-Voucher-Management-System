-- =====================================================================
--  Expense Voucher Management System - Database schema
--  Database : MySQL 8.0.16 or newer (CHECK constraints are enforced)
--
--  WARNING: this script DROPS and re-creates the three application
--  tables, so every existing voucher is deleted. Run it only to set the
--  project up for the first time or to reset it.
--
--  Easiest way to run it:   npm run db:setup      (from the project root)
--  Manual alternative:      open this file in MySQL Workbench and execute it,
--                           then do the same with seed.sql
-- =====================================================================

CREATE DATABASE IF NOT EXISTS prachay_expense_vouchers
  CHARACTER SET utf8mb4
  COLLATE utf8mb4_unicode_ci;

USE prachay_expense_vouchers;

-- Children first, because of the foreign keys.
DROP TABLE IF EXISTS voucher_history;
DROP TABLE IF EXISTS vouchers;
DROP TABLE IF EXISTS voucher_sequences;
DROP TABLE IF EXISTS users;

-- ---------------------------------------------------------------------
--  users : everybody who can log in (employees, the director, accounts)
-- ---------------------------------------------------------------------
CREATE TABLE users (
  id            INT UNSIGNED NOT NULL AUTO_INCREMENT,
  full_name     VARCHAR(100) NOT NULL,
  email         VARCHAR(150) NOT NULL,
  password_hash VARCHAR(255) NOT NULL,              -- bcrypt hash, never the plain password
  role          ENUM('EMPLOYEE', 'DIRECTOR', 'ACCOUNTS') NOT NULL,
  employee_code VARCHAR(20)  NULL,                  -- the optional "Employee ID" printed on a voucher
  department    VARCHAR(100) NULL,                  -- the user's own department (pre-fills the form)
  is_active     TINYINT(1)   NOT NULL DEFAULT 1,    -- 0 = account disabled, cannot log in
  created_at    TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at    TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,

  PRIMARY KEY (id),
  UNIQUE KEY uq_users_email (email),
  UNIQUE KEY uq_users_employee_code (employee_code)
) ENGINE = InnoDB;

-- ---------------------------------------------------------------------
--  voucher_sequences : one counter per year, used to build voucher
--  numbers such as EV-2026-00042. The row is locked while a voucher is
--  being created, so two people can never receive the same number.
-- ---------------------------------------------------------------------
CREATE TABLE voucher_sequences (
  seq_year    SMALLINT UNSIGNED NOT NULL,
  last_number INT UNSIGNED      NOT NULL DEFAULT 0,   -- the last number handed out in that year

  PRIMARY KEY (seq_year)
) ENGINE = InnoDB;

-- ---------------------------------------------------------------------
--  vouchers : one row per expense voucher
-- ---------------------------------------------------------------------
CREATE TABLE vouchers (
  id                      INT UNSIGNED  NOT NULL AUTO_INCREMENT,
  voucher_number          VARCHAR(20)   NOT NULL,   -- generated by the server, e.g. EV-2026-00042
  employee_id             INT UNSIGNED  NOT NULL,   -- who created the voucher (employee name comes from users)

  -- Details entered by the employee. Nobody else can change these.
  voucher_date            DATE          NOT NULL,
  expense_date            DATE          NOT NULL,
  department              VARCHAR(100)  NOT NULL,
  expense_title           VARCHAR(150)  NOT NULL,
  expense_category        VARCHAR(50)   NOT NULL,
  expense_description     TEXT          NULL,
  amount                  DECIMAL(12, 2) NOT NULL,  -- DECIMAL keeps money exact (no floating point rounding)
  employee_signature_path VARCHAR(255)  NULL,       -- path inside server/uploads, never a full disk path

  -- Workflow / approval information.
  status                  ENUM('DRAFT', 'PENDING_APPROVAL', 'APPROVED', 'REJECTED') NOT NULL DEFAULT 'DRAFT',
  submitted_at            TIMESTAMP     NULL DEFAULT NULL,
  reviewed_by             INT UNSIGNED  NULL,       -- the director who approved or rejected
  director_signature_path VARCHAR(255)  NULL,
  approved_at             TIMESTAMP     NULL DEFAULT NULL,   -- "Approval Date"
  rejected_at             TIMESTAMP     NULL DEFAULT NULL,
  rejection_reason        VARCHAR(500)  NULL,

  -- Audit information.
  created_at              TIMESTAMP     NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at              TIMESTAMP     NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,

  PRIMARY KEY (id),
  UNIQUE KEY uq_vouchers_number (voucher_number),

  -- Indexes for the list screens (filtering and sorting).
  KEY idx_vouchers_employee_status (employee_id, status),
  KEY idx_vouchers_status (status),
  KEY idx_vouchers_expense_date (expense_date),
  KEY idx_vouchers_department (department),
  KEY idx_vouchers_category (expense_category),
  KEY idx_vouchers_created_at (created_at),

  CONSTRAINT fk_vouchers_employee FOREIGN KEY (employee_id) REFERENCES users (id),
  CONSTRAINT fk_vouchers_reviewer FOREIGN KEY (reviewed_by) REFERENCES users (id),

  -- Business rules repeated at database level as a last line of defence.
  CONSTRAINT chk_vouchers_amount_positive
    CHECK (amount > 0),
  CONSTRAINT chk_vouchers_submitted_has_employee_signature
    CHECK (status = 'DRAFT' OR employee_signature_path IS NOT NULL),
  CONSTRAINT chk_vouchers_approved_has_director_signature
    CHECK (status <> 'APPROVED' OR (director_signature_path IS NOT NULL AND approved_at IS NOT NULL)),
  CONSTRAINT chk_vouchers_rejected_has_reason
    CHECK (status <> 'REJECTED' OR (rejection_reason IS NOT NULL AND rejected_at IS NOT NULL))
) ENGINE = InnoDB;

-- ---------------------------------------------------------------------
--  voucher_history : audit trail. One row every time a voucher is
--  created, edited, submitted, approved or rejected.
-- ---------------------------------------------------------------------
CREATE TABLE voucher_history (
  id           INT UNSIGNED NOT NULL AUTO_INCREMENT,
  voucher_id   INT UNSIGNED NOT NULL,
  action       ENUM('CREATED', 'UPDATED', 'SUBMITTED', 'APPROVED', 'REJECTED') NOT NULL,
  from_status  ENUM('DRAFT', 'PENDING_APPROVAL', 'APPROVED', 'REJECTED') NULL,
  to_status    ENUM('DRAFT', 'PENDING_APPROVAL', 'APPROVED', 'REJECTED') NOT NULL,
  performed_by INT UNSIGNED NOT NULL,
  remarks      VARCHAR(500) NULL,                   -- e.g. the rejection reason
  created_at   TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,

  PRIMARY KEY (id),
  KEY idx_history_voucher (voucher_id, created_at),
  KEY idx_history_created_at (created_at),

  -- Only drafts can be deleted, and their history goes with them.
  CONSTRAINT fk_history_voucher FOREIGN KEY (voucher_id) REFERENCES vouchers (id) ON DELETE CASCADE,
  CONSTRAINT fk_history_user    FOREIGN KEY (performed_by) REFERENCES users (id)
) ENGINE = InnoDB;
